#!/usr/bin/env python3
"""Turn Wycheproof's ed25519_test.json into tests/wycheproof_ed25519.h.

    python tests/gen_wycheproof.py path/to/ed25519_test.json > tests/wycheproof_ed25519.h

Source: https://github.com/C2SP/wycheproof (testvectors_v1/ed25519_test.json),
Apache License 2.0. The generated header is checked in, so the tests don't need
the network.
"""
import json
import sys


def c_bytes(h: str) -> str:
    return '"' + "".join(f"\\x{h[i:i + 2]}" for i in range(0, len(h), 2)) + '"'


def main():
    d = json.load(open(sys.argv[1], encoding="utf-8"))
    rows = []
    for g in d["testGroups"]:
        pub = g["publicKey"]["pk"]
        for t in g["tests"]:
            res = {"valid": 1, "invalid": 0, "acceptable": 2}[t["result"]]
            sig = t["sig"]
            rows.append(f'  {{{t["tcId"]}, {res}, {c_bytes(pub)}, {c_bytes(t["msg"])}, {len(t["msg"]) // 2}, '
                        f'{c_bytes(sig)}, {len(sig) // 2}}},')
    print("/* generated by tests/gen_wycheproof.py from Wycheproof's ed25519_test.json")
    print(f" * ({d.get('numberOfTests')} tests; https://github.com/C2SP/wycheproof, Apache License 2.0) */")
    print("typedef struct { int id, result; const char* pub; const char* msg; unsigned msg_len;")
    print("                 const char* sig; unsigned sig_len; } wp_ed25519_t;   /* result: 1 valid, 0 invalid, 2 acceptable */")
    print("static const wp_ed25519_t wp_ed25519[] = {")
    print("\n".join(rows))
    print("};")


if __name__ == "__main__":
    main()
