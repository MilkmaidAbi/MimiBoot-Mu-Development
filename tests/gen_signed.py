"""
Make signed image headers for the C tests with the same code mbtool uses,
so the tests check Python signing against C verification.

    python tests/gen_signed.py > tests/gen_signed.h
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))
import mb_ed25519 as ed  # noqa: E402
import mbtool  # noqa: E402

RFC1_SECRET = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
OTHER_SECRET = bytes(range(1, 33))


def payload(seed, size):
    """Same generator as make_payload() in test_mimiboot.c (xorshift32)."""
    x = (seed * 2654435761 + 1) & 0xFFFFFFFF
    out = bytearray(size)
    for i in range(size):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out[i] = x & 0xFF
    return bytes(out)


def c_array(name, data):
    rows = ", ".join("0x%02x" % b for b in data)
    return "__attribute__((unused)) static const uint8_t %s[%d] = { %s };\n" % (name, len(data), rows)


P256_SECRET = mbtool.Secret("p256", bytes.fromhex("C9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721"))
P256_OTHER = mbtool.Secret("p256", bytes(range(2, 34)))

cases = [
    ("signed_good", 11, 40000, RFC1_SECRET, mbtool.parse_version("2.0.0"), 1),
    ("signed_other_key", 12, 40000, OTHER_SECRET, mbtool.parse_version("2.0.1"), 1),
    ("signed_p256", 13, 40000, P256_SECRET, mbtool.parse_version("3.0.0"), 1),
    ("signed_p256_other", 14, 40000, P256_OTHER, mbtool.parse_version("3.0.1"), 1),
]
print("/* generated by tests/gen_signed.py - do not edit */")
for name, seed, size, secret, version, secver in cases:
    hdr = mbtool.build_header(payload(seed, size), name, version, secver, target="sim", arch=mbtool.ARCH_ARM,
                              secret=secret, build_time=0)
    sig = hdr[mbtool.SIGNED_BYTES:mbtool.SIGNED_BYTES + 64]
    if isinstance(secret, mbtool.Secret):
        import mb_p256  # noqa: E402
        assert mb_p256.verify(secret.public, hdr[:mbtool.SIGNED_BYTES], sig)
    else:
        assert ed.verify(ed.public_key(secret), hdr[:mbtool.SIGNED_BYTES], sig)
    print("#define %s_SEED %d\n#define %s_SIZE %d" % (name.upper(), seed, name.upper(), size))
    print(c_array(name + "_hdr", hdr))

# signed boot configs (CFG_SIGNED), with mbtool's config_signature()
CFG_TEXT = b"default rescue\nentry rescue\n title Signed rescue\n slot g\n args signed=1\n"
for name, version, secret in (("cfg_v5", 5, RFC1_SECRET), ("cfg_v3", 3, RFC1_SECRET), ("cfg_other_key", 9, OTHER_SECRET)):
    sig = mbtool.config_signature(secret, b"sim", version, CFG_TEXT)
    print("#define %s_VERSION %d" % (name.upper(), version))
    print(c_array(name + "_sig", sig))
print(c_array("cfg_text", CFG_TEXT))


# An MCUboot image as tests/test_profile.c's put_mcuboot() builds it (header
# 0x200, v1.2.3, 1024-byte body), signed the way imgtool's ECDSA P-256 does:
# over the image's SHA-256 digest, DER-encoded, in an ECDSA_SIG TLV.
def der_int(v):
    b = v.to_bytes(32, "big").lstrip(b"\0") or b"\0"
    if b[0] & 0x80:
        b = b"\0" + b
    return b"\x02" + bytes([len(b)]) + b


def mcuboot_digest(seed):
    import hashlib
    import struct
    img = bytearray(0x200 + 1024)
    struct.pack_into("<I", img, 0, 0x96f3b83d)
    struct.pack_into("<H", img, 8, 0x200)
    struct.pack_into("<I", img, 12, 1024)
    img[20:23] = b"\x01\x02\x03"
    img[0x200:] = payload(seed, 1024)
    return hashlib.sha256(bytes(img)).digest()


import mb_p256  # noqa: E402
for seed in (7,):
    raw = mb_p256.sign_digest(P256_SECRET.raw, mcuboot_digest(seed))
    body = der_int(int.from_bytes(raw[:32], "big")) + der_int(int.from_bytes(raw[32:], "big"))
    der = b"\x30" + bytes([len(body)]) + body
    print("#define MCUBOOT_ECDSA_SEED %d" % seed)
    print(c_array("mcuboot_ecdsa_der", der))
